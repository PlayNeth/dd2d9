#!/usr/bin/env python3
# Generates winmm.def and stubs.cpp from winmm.exports ("ordinal name" per line, the name
# empty for an export by ordinal only): winmm.dll's exports as Wine has them (11.22), with
# their ordinals. Run it after changing winmm.exports; both outputs are kept in the tree.
import os
here = os.path.dirname(os.path.abspath(__file__))
exports = []
for line in open(os.path.join(here, 'winmm.exports')):
    parts = line.split()
    if parts:
        exports.append((int(parts[0]), parts[1] if len(parts) > 1 else None))
with open(os.path.join(here, 'winmm.def'), 'w') as f:
    f.write('; Generated by gen.py from winmm.exports.\nLIBRARY winmm.dll\nEXPORTS\n')
    for i, (ordinal, name) in enumerate(exports):
        f.write(f'    {name} = dd2d9_stub{i} @{ordinal}\n' if name else f'    dd2d9_stub{i} @{ordinal} NONAME\n')
with open(os.path.join(here, 'stubs.cpp'), 'w') as f:
    f.write('// Generated by gen.py from winmm.exports: one jump per export, through the address\n'
            '// winmm.cpp looked up in the next winmm.dll.\n'
            '#include "loader.h"\n\n'
            f'extern "C" void* dd2d9_next[{len(exports)}];\n'
            f'void* dd2d9_next[{len(exports)}];\n'
            'const LoaderExport kLoaderExports[] = {\n')
    for ordinal, name in exports:
        f.write(f'    {{{ordinal}, {chr(34) + name + chr(34) if name else "nullptr"}}},\n')
    f.write('};\n'
            f'const unsigned kLoaderExportCount = {len(exports)};\n\n'
            'asm(".text\\n"\n')
    for i, _ in enumerate(exports):
        f.write(f'    ".globl _dd2d9_stub{i}\\n_dd2d9_stub{i}: jmp *_dd2d9_next+{4 * i}\\n"\n')
    f.write(');\n')
