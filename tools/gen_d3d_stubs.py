#!/usr/bin/env python3
"""Generates src/d3dstubs.h: one stub class per legacy Direct3D interface.

Every method except QueryInterface/AddRef/Release logs once and returns
DDERR_UNSUPPORTED; d3dproxy.cpp derives from these classes and overrides the
methods it implements. Signatures are copied verbatim from mingw-w64's d3d.h,
so the compiler checks every override against the SDK.

Usage: gen_d3d_stubs.py [path/to/d3d.h] > src/d3dstubs.h
"""
import re
import sys

INTERFACES = [
    "IDirect3D", "IDirect3D2", "IDirect3D3", "IDirect3D7",
    "IDirect3DDevice", "IDirect3DDevice2", "IDirect3DDevice3", "IDirect3DDevice7",
    "IDirect3DViewport", "IDirect3DViewport2", "IDirect3DViewport3",
    "IDirect3DMaterial", "IDirect3DMaterial2", "IDirect3DMaterial3",
    "IDirect3DTexture", "IDirect3DTexture2",
]
SKIP = {"QueryInterface", "AddRef", "Release"}


def methods(header, name):
    m = re.search(r"DECLARE_INTERFACE_\(%s,\s*\w+\)\s*\{(.*?)\n\};" % name, header, re.S)
    if not m:
        sys.exit("interface %s not found" % name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    decls = " ".join(body.split())  # join multi-line declarations
    out = []
    for d in re.finditer(r"STDMETHOD(_\((\w+),\s*(\w+)\)|\((\w+)\))\(THIS_?\s*(.*?)\)\s*PURE;", decls):
        ret = d.group(2) or "HRESULT"
        meth = d.group(3) or d.group(4)
        params = d.group(5).strip()
        if meth not in SKIP:
            out.append((ret, meth, params))
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "/usr/i686-w64-mingw32/include/d3d.h"
    header = open(path).read()
    print("// Generated by tools/gen_d3d_stubs.py from mingw-w64's d3d.h. Do not edit.")
    print("#pragma once")
    print('#include "common.h"')
    print("#include <d3d.h>")
    print()
    print("namespace dd2d9 {")
    for name in INTERFACES:
        print()
        print("class %sStub : public %s {" % (name, name))
        print("public:")
        for ret, meth, params in methods(header, name):
            body = 'DD2D9_STUB("%s::%s"); return %s;' % (
                name, meth, "DDERR_UNSUPPORTED" if ret == "HRESULT" else "0")
            if ret == "HRESULT":
                print("    STDMETHOD(%s)(%s) override { %s }" % (meth, params, body))
            else:
                print("    STDMETHOD_(%s, %s)(%s) override { %s }" % (ret, meth, params, body))
        print("};")
    print()
    print("}  // namespace dd2d9")


if __name__ == "__main__":
    main()
